void *mgl_proc_address(const char *name) {
    size_t i;
    if (name == NULL)
        return NULL;
    for (i = 0; i < sizeof(entries) / sizeof(entries[0]); ++i) {
        if (strcmp(entries[i].name, name) == 0) {
            union {
                void (*fn)(void);
                void *ptr;
            } cast;

            cast.fn = entries[i].proc;
            return cast.ptr;
        }
    }
    return NULL;
}
