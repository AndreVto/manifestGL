from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
header = (root / "src/native/dispatch.h").read_text()
pattern = re.compile(r"\s+([^;\n]*?)\(\*(gles\w+)\)\((.*?)\);", re.S)
functions = [(m.group(1).strip(), m.group(2), [s.strip() for s in m.group(3).split(",")])
             for m in pattern.finditer(header)]
exclude = {"glesGetError", "glesBindFramebuffer"}


def encoded(type_name, arg):
    if type_name == "GLfloat":
        return f"mgl_gles_trace_float({arg})"
    if type_name == "GLclampd":
        return f"mgl_gles_trace_double({arg})"
    if "*" in type_name or type_name == "GLsync":
        return f"(uint64_t)(uintptr_t){arg}"
    return f"(uint64_t){arg}"


lines = ["/* Generated by tools/generate_gles_trace.py. */", ""]
for return_type, name, types in functions:
    if name in exclude:
        continue
    types = [] if types == ["void"] else types
    args = [f"arg{i}" for i in range(len(types))]
    signature = ", ".join(f"{type_name} {arg}" for type_name, arg in zip(types, args)) or "void"
    values = ", ".join(args)
    lines += [
        f"static {return_type} mgl_trace_{name}({signature}) {{",
        "    struct mgl_context *ctx = mgl_context_current();",
        "    const struct mgl_native_dispatch *raw = mgl_trace_current_raw(ctx);",
    ]
    if types:
        encoded_args = ", ".join(encoded(t, a) for t, a in zip(types, args))
        lines.append(f"    const uint64_t arguments[] = {{{encoded_args}}};")
        lines.append(f"    mgl_gles_trace_before(ctx, raw, \"{name}\", arguments, {len(types)}u,")
    else:
        lines.append(f"    mgl_gles_trace_before(ctx, raw, \"{name}\", NULL, 0u,")
    lines.append("                          __builtin_return_address(0));")
    call = f"raw->{name}({values})"
    if return_type == "void":
        lines.append(f"    {call};")
    else:
        lines.append(f"    {return_type} result = {call};")
    lines += [
        f"    mgl_gles_trace_after(ctx, raw, \"{name}\");",
    ]
    if return_type != "void":
        lines.append("    return result;")
    lines += ["}", ""]

lines += ["static int mgl_gles_trace_install(struct mgl_native_dispatch *native) {",
          "    struct mgl_native_dispatch *raw = malloc(sizeof(*raw));",
          "    if (raw == NULL)", "        return 0;", "    *raw = *native;",
          "    native->trace_raw = raw;"]
for return_type, name, types in functions:
    if name in exclude:
        continue
    lines += [f"    if (raw->{name} != NULL)",
              f"        native->{name} = mgl_trace_{name};"]
lines += ["    return 1;", "}", ""]
output = root / "src/native/dispatch_trace.generated.inc"
contents = "\n".join(lines)
if sys.argv[1:] == ["--check"]:
    if not output.is_file() or output.read_text() != contents:
        print(f"Outdated GLES trace wrappers: run python3 tools/generate_gles_trace.py", file=sys.stderr)
        raise SystemExit(1)
elif len(sys.argv) == 1:
    if not output.is_file() or output.read_text() != contents:
        output.write_text(contents)
else:
    raise SystemExit("usage: generate_gles_trace.py [--check]")
print(f"Verified {len(functions) - len(exclude)} wrappers" if len(sys.argv) > 1
      else f"Generated {len(functions) - len(exclude)} wrappers")
