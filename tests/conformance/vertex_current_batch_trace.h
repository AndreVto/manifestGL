/* Legacy attribute tests compare defined components, errors, and invalid-index
 * preservation. Unspecified component values are excluded from reference parity. */
static int vcb_close(GLfloat a, GLfloat b) {
    /* Normalized integer zero requires a narrower comparison tolerance. */
    const GLfloat tolerance = b > 0.f && b < 0.00000001f ? 0.00000000001f : 0.0000001f;
    return a - b < tolerance && b - a < tolerance;
}

static void vcb_float(const char *label, unsigned components, GLfloat x, GLfloat y, GLfloat z,
                      GLfloat w) {
    GLenum call_error = glGetError();
    GLfloat current[4] = {-999.f, -999.f, -999.f, -999.f};
    glGetVertexAttribfv(3u, GL_CURRENT_VERTEX_ATTRIB, current);
    printf("vcb_%s %d 0x%x 0x%x\n", label,
           vcb_close(current[0], x) && (components < 2u || vcb_close(current[1], y)) &&
               (components < 3u || vcb_close(current[2], z)) &&
               (components < 4u || vcb_close(current[3], w)),
           (unsigned)call_error, (unsigned)glGetError());
}

static void vcb_integer(const char *label, GLint x, GLint y, GLint z, GLint w) {
    GLenum call_error = glGetError();
    GLint current[4] = {-999, -999, -999, -999};
    glGetVertexAttribIiv(3u, GL_CURRENT_VERTEX_ATTRIB, current);
    printf("vcb_%s %d 0x%x 0x%x\n", label,
           current[0] == x && current[1] == y && current[2] == z && current[3] == w,
           (unsigned)call_error, (unsigned)glGetError());
}

static void vcb_unsigned(const char *label, GLuint x, GLuint y, GLuint z, GLuint w) {
    GLenum call_error = glGetError();
    GLuint current[4] = {999u, 999u, 999u, 999u};
    glGetVertexAttribIuiv(3u, GL_CURRENT_VERTEX_ATTRIB, current);
    printf("vcb_%s %d 0x%x 0x%x\n", label,
           current[0] == x && current[1] == y && current[2] == z && current[3] == w,
           (unsigned)call_error, (unsigned)glGetError());
}

