static void ub_row(const char *name, const char *case_name) {
    GLint program = -1;
    GLenum error = glGetError();
    glGetIntegerv(GL_CURRENT_PROGRAM, &program);
    printf("ub_%s_%s 0x%04x %d 0x%04x\n", name, case_name, (unsigned)error,
           program != 0 && program == (GLint)ub_expected_program, (unsigned)glGetError());
}

