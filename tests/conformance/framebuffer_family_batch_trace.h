#ifndef MGL_FRAMEBUFFER_FAMILY_BATCH_TRACE_H
#define MGL_FRAMEBUFFER_FAMILY_BATCH_TRACE_H
#include "mgl/gl.h"
#include <stdio.h>

static void fbf_err(const char *name) {
    printf("fbf_%s 0x%04x\n", name, (unsigned)glGetError());
}

static void fbf_trace(void) {
    GLuint fb = 0, rb = 0, tex = 0;
    GLint v = -777;
    GLenum color = GL_COLOR_ATTACHMENT0;
    GLenum back = GL_BACK;
    GLenum none = GL_NONE;
    GLsizei count = 1;
    GLfloat fv[4] = {0.f, 0.f, 0.f, 1.f};
    GLint iv[4] = {1, 2, 3, 4};
    GLuint uv[4] = {1, 2, 3, 4};
    glCreateFramebuffers(1, &fb);
    fbf_err("create_fb");
    glCreateRenderbuffers(1, &rb);
    fbf_err("create_rb");
    glNamedRenderbufferStorage(rb, GL_RGBA4, 4, 4);
    fbf_err("rb_storage");
    glGetNamedRenderbufferParameteriv(rb, GL_RENDERBUFFER_WIDTH, &v);
    printf("fbf_rb_width %d 0x%04x\n", v == 4, (unsigned)glGetError());
    glNamedFramebufferRenderbuffer(fb, color, GL_RENDERBUFFER, rb);
    fbf_err("attach_rb");
    glGetNamedFramebufferAttachmentParameteriv(fb, color, GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE,
                                               &v);
    printf("fbf_rb_att_type %d 0x%04x\n", v == (GLint)GL_RENDERBUFFER, (unsigned)glGetError());
    glNamedFramebufferDrawBuffer(fb, color);
    fbf_err("named_draw_buffer");
    glNamedFramebufferDrawBuffers(fb, 1, &color);
    fbf_err("named_draw_buffers");
    glNamedFramebufferReadBuffer(fb, color);
    fbf_err("named_read_buffer");
    glNamedRenderbufferStorageMultisample(rb, 0, GL_RGBA4, 4, 4);
    fbf_err("rb_multi");
    glBindFramebuffer(GL_FRAMEBUFFER, fb);
    fbf_err("bind_fb");
    glDrawBuffer(color);
    fbf_err("draw_buffer");
    glReadBuffer(color);
    fbf_err("read_buffer");
    glGetFramebufferAttachmentParameteriv(GL_FRAMEBUFFER, color,
                                          GL_FRAMEBUFFER_ATTACHMENT_OBJECT_NAME, &v);
    printf("fbf_bound_rb_name %d 0x%04x\n", v == (GLint)rb, (unsigned)glGetError());
    glInvalidateFramebuffer(GL_FRAMEBUFFER, 1, &color);
    fbf_err("invalidate_bound");
    glInvalidateNamedFramebufferData(fb, 1, &color);
    fbf_err("invalidate_named");
    glInvalidateNamedFramebufferSubData(fb, 1, &color, 0, 0, 2, 2);
    fbf_err("invalidate_sub");
    glCheckNamedFramebufferStatus(fb, GL_FRAMEBUFFER);
    fbf_err("named_check");
    glBlitNamedFramebuffer(fb, fb, 0, 0, 0, 0, 0, 0, 0, 0, 0, GL_NEAREST);
    fbf_err("blit_zero");
    glClearBufferiv(GL_STENCIL, 0, iv);
    fbf_err("clear_iv");
    glClearBufferuiv(GL_COLOR, 0, uv);
    fbf_err("clear_uiv");
    glClearBufferfv(GL_COLOR, 0, fv);
    fbf_err("clear_fv");
    glClearBufferfi(GL_DEPTH_STENCIL, 0, 1.f, 0);
    fbf_err("clear_fi");
    glClearNamedFramebufferiv(fb, GL_STENCIL, 0, iv);
    fbf_err("clear_named_iv");
    glClearNamedFramebufferuiv(fb, GL_COLOR, 0, uv);
    fbf_err("clear_named_uiv");
    glClearNamedFramebufferfv(fb, GL_COLOR, 0, fv);
    fbf_err("clear_named_fv");
    glClearNamedFramebufferfi(fb, GL_DEPTH_STENCIL, 0, 1.f, 0);
    fbf_err("clear_named_fi");
    glGenTextures(1, &tex);
    glBindTexture(GL_TEXTURE_2D, tex);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, 4, 4, 0, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
    fbf_err("tex_setup");
    glFramebufferTexture2D(GL_FRAMEBUFFER, color, GL_TEXTURE_2D, tex, 0);
    fbf_err("attach_tex_2d");
    glGetFramebufferAttachmentParameteriv(GL_FRAMEBUFFER, color,
                                          GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE, &v);
    printf("fbf_tex_type %d 0x%04x\n", v == (GLint)GL_TEXTURE, (unsigned)glGetError());
    glFramebufferTexture3D(GL_FRAMEBUFFER, color, GL_TEXTURE_3D, 0, 0, 0);
    fbf_err("detach_tex_3d");
    glFramebufferTextureLayer(GL_FRAMEBUFFER, color, 0, 0, 0);
    fbf_err("detach_tex_layer");

    glNamedFramebufferRenderbuffer(fb, color, GL_RENDERBUFFER, rb);
    fbf_err("reattach_rb");
    glBegin(GL_POINTS);
    glInvalidateFramebuffer(GL_FRAMEBUFFER, 1, &color);
    glEnd();
    fbf_err("invalidate_begin");
    glBegin(GL_POINTS);
    glInvalidateFramebuffer(0xDEADu, -1, &color);
    glEnd();
    fbf_err("invalidate_bad_begin");
    glBegin(GL_POINTS);
    glInvalidateNamedFramebufferData(fb, 1, &color);
    glEnd();
    fbf_err("named_invalidate_begin");
    glBegin(GL_POINTS);
    glInvalidateNamedFramebufferData(999999u, -1, &color);
    glEnd();
    fbf_err("named_invalidate_bad_begin");
    glBegin(GL_POINTS);
    glInvalidateNamedFramebufferSubData(fb, 1, &color, 0, 0, 2, 2);
    glEnd();
    fbf_err("named_sub_begin");
    glBegin(GL_POINTS);
    glInvalidateNamedFramebufferSubData(fb, -1, &color, 0, 0, -1, -1);
    glEnd();
    fbf_err("named_sub_bad_begin");
    glBegin(GL_POINTS);
    glNamedFramebufferDrawBuffer(fb, color);
    glEnd();
    fbf_err("named_draw_begin");
    glBegin(GL_POINTS);
    glNamedFramebufferDrawBuffers(fb, 1, &color);
    glEnd();
    fbf_err("named_draws_begin");
    glBegin(GL_POINTS);
    glNamedFramebufferReadBuffer(fb, color);
    glEnd();
    fbf_err("named_read_begin");
    glBegin(GL_POINTS);
    glBlitNamedFramebuffer(fb, fb, 0, 0, 1, 1, 0, 0, 1, 1, GL_COLOR_BUFFER_BIT, GL_NEAREST);
    glEnd();
    fbf_err("named_blit_begin");
    glBegin(GL_POINTS);
    glNamedFramebufferRenderbuffer(fb, color, GL_RENDERBUFFER, rb);
    glEnd();
    fbf_err("named_rb_begin");
    v = -777;
    glBegin(GL_POINTS);
    glGetNamedFramebufferAttachmentParameteriv(fb, color, GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE,
                                               &v);
    glEnd();
    printf("fbf_named_get_begin %d 0x%04x\n", v == -777, (unsigned)glGetError());
    glBegin(GL_POINTS);
    glFramebufferTexture2D(GL_FRAMEBUFFER, color, GL_TEXTURE_2D, tex, 0);
    glEnd();
    fbf_err("tex2d_begin");
    glBegin(GL_POINTS);
    glFramebufferTexture3D(GL_FRAMEBUFFER, color, GL_TEXTURE_3D, tex, 0, 0);
    glEnd();
    fbf_err("tex3d_begin");
    glBegin(GL_POINTS);
    glFramebufferTextureLayer(GL_FRAMEBUFFER, color, tex, 0, 0);
    glEnd();
    fbf_err("tex_layer_begin");
    glBegin(GL_POINTS);
    glClearBufferiv(GL_STENCIL, 0, iv);
    glEnd();
    fbf_err("clear_iv_begin");
    glBegin(GL_POINTS);
    glClearBufferuiv(GL_COLOR, 0, uv);
    glEnd();
    fbf_err("clear_uiv_begin");
    glBegin(GL_POINTS);
    glClearBufferfv(GL_COLOR, 0, fv);
    glEnd();
    fbf_err("clear_fv_begin");
    glBegin(GL_POINTS);
    glClearBufferfi(GL_DEPTH_STENCIL, 0, 1.f, 0);
    glEnd();
    fbf_err("clear_fi_begin");
    glBegin(GL_POINTS);
    glClearNamedFramebufferiv(fb, GL_STENCIL, 0, iv);
    glEnd();
    fbf_err("named_clear_iv_begin");
    glBegin(GL_POINTS);
    glClearNamedFramebufferuiv(fb, GL_COLOR, 0, uv);
    glEnd();
    fbf_err("named_clear_uiv_begin");
    glBegin(GL_POINTS);
    glClearNamedFramebufferfv(fb, GL_COLOR, 0, fv);
    glEnd();
    fbf_err("named_clear_fv_begin");
    glBegin(GL_POINTS);
    glClearNamedFramebufferfi(fb, GL_DEPTH_STENCIL, 0, 1.f, 0);
    glEnd();
    fbf_err("named_clear_fi_begin");
    glBegin(GL_POINTS);
    glNamedRenderbufferStorage(rb, GL_RGBA4, 8, 8);
    glEnd();
    fbf_err("named_rb_storage_begin");
    glBegin(GL_POINTS);
    glNamedRenderbufferStorageMultisample(rb, 0, GL_RGBA4, 8, 8);
    glEnd();
    fbf_err("named_rb_multi_begin");
    v = -777;
    glBegin(GL_POINTS);
    glGetNamedRenderbufferParameteriv(rb, GL_RENDERBUFFER_WIDTH, &v);
    glEnd();
    printf("fbf_named_rb_get_begin %d 0x%04x\n", v == -777, (unsigned)glGetError());
    glGetNamedRenderbufferParameteriv(rb, GL_RENDERBUFFER_WIDTH, &v);
    printf("fbf_rb_preserved %d 0x%04x\n", v == 4, (unsigned)glGetError());
    glGetNamedFramebufferAttachmentParameteriv(fb, color, GL_FRAMEBUFFER_ATTACHMENT_OBJECT_TYPE,
                                               &v);
    printf("fbf_attachment_preserved %d 0x%04x\n", v == (GLint)GL_RENDERBUFFER,
           (unsigned)glGetError());
    glBindFramebuffer(GL_FRAMEBUFFER, 0);
    glDeleteTextures(1, &tex);
    glDeleteFramebuffers(1, &fb);
    glDeleteRenderbuffers(1, &rb);
    (void)count;
    (void)back;
    (void)none;
    fbf_err("cleanup");
}
#endif
