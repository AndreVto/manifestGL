#ifndef MGL_CORE_TEXTURE_DSA_CA_TRACE_H
#define MGL_CORE_TEXTURE_DSA_CA_TRACE_H
#include "mgl/gl.h"
#include <stdio.h>

static void ca_err(const char *name) {
    printf("ca_%s 0x%04x\n", name, (unsigned)glGetError());
}

static void core_texture_dsa_ca_trace(void) {
    GLuint tex = 0, tex3 = 0, texms = 0, texmsa = 0, texmsb = 0, texmsab = 0, texmsimg = 0,
           texmsimga = 0;
    GLint i = -1, iv[4] = {-1, -1, -1, -1};
    GLuint uv[4] = {0, 0, 0, 0};
    GLfloat f = -1.f, fv[4] = {-1.f, -1.f, -1.f, -1.f};
    const GLint col[4] = {1, 0, 1, 1};
    const GLuint ucol[4] = {1, 2, 3, 4};
    const GLfloat fcol[4] = {.25f, .50f, .75f, 1.f};
    const GLubyte bytes[32] = {0};
    glCreateTextures(GL_TEXTURE_2D, 1, &tex);
    glCreateTextures(GL_TEXTURE_3D, 1, &tex3);
    glCreateTextures(GL_TEXTURE_2D_MULTISAMPLE, 1, &texms);
    glCreateTextures(GL_TEXTURE_2D_MULTISAMPLE_ARRAY, 1, &texmsa);
    glCreateTextures(GL_TEXTURE_2D_MULTISAMPLE, 1, &texmsb);
    glCreateTextures(GL_TEXTURE_2D_MULTISAMPLE_ARRAY, 1, &texmsab);
    glCreateTextures(GL_TEXTURE_2D_MULTISAMPLE, 1, &texmsimg);
    glCreateTextures(GL_TEXTURE_2D_MULTISAMPLE_ARRAY, 1, &texmsimga);
    ca_err("setup");
    glTextureParameteri(tex, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    ca_err("Parameteri_valid");
    glGetTextureParameteriv(tex, GL_TEXTURE_WRAP_S, &i);
    printf("ca_wrap_s %d 0x%04x\n", i, (unsigned)glGetError());
    glTextureParameterf(tex, GL_TEXTURE_MIN_LOD, 2.75f);
    ca_err("Parameterf_valid");
    glGetTextureParameterfv(tex, GL_TEXTURE_MIN_LOD, &f);
    printf("ca_lod %.2f 0x%04x\n", f, (unsigned)glGetError());
    glTextureParameteriv(tex, GL_TEXTURE_BORDER_COLOR, col);
    ca_err("Parameteriv_valid");
    glGetTextureParameteriv(tex, GL_TEXTURE_BORDER_COLOR, iv);
    printf("ca_border_iv %d %d %d %d 0x%04x\n", iv[0], iv[1], iv[2], iv[3], (unsigned)glGetError());
    glTextureParameterfv(tex, GL_TEXTURE_BORDER_COLOR, fcol);
    ca_err("Parameterfv_valid");
    glGetTextureParameterfv(tex, GL_TEXTURE_BORDER_COLOR, fv);
    printf("ca_border_fv %.2f %.2f %.2f %.2f 0x%04x\n", fv[0], fv[1], fv[2], fv[3],
           (unsigned)glGetError());
    glTextureParameterIiv(tex, GL_TEXTURE_BORDER_COLOR, col);
    ca_err("ParameterIiv_valid");
    glGetTextureParameterIiv(tex, GL_TEXTURE_BORDER_COLOR, iv);
    printf("ca_border_iiv %d %d %d %d 0x%04x\n", iv[0], iv[1], iv[2], iv[3],
           (unsigned)glGetError());
    glTextureParameterIuiv(tex, GL_TEXTURE_BORDER_COLOR, ucol);
    ca_err("ParameterIuiv_valid");
    glGetTextureParameterIuiv(tex, GL_TEXTURE_BORDER_COLOR, uv);
    printf("ca_border_iuiv %u %u %u %u 0x%04x\n", uv[0], uv[1], uv[2], uv[3],
           (unsigned)glGetError());
    glBegin(GL_POINTS);
    glTextureParameteri(tex, 0xDEADu, 123);
    glEnd();
    ca_err("Parameteri_begin_bad");
    glBegin(GL_POINTS);
    glTextureParameterf(tex, 0xDEADu, 1.f);
    glEnd();
    ca_err("Parameterf_begin_bad");
    glBegin(GL_POINTS);
    glTextureParameteriv(tex, 0xDEADu, col);
    glEnd();
    ca_err("Parameteriv_begin_bad");
    glBegin(GL_POINTS);
    glTextureParameterfv(tex, 0xDEADu, fcol);
    glEnd();
    ca_err("Parameterfv_begin_bad");
    glBegin(GL_POINTS);
    glTextureParameterIiv(tex, 0xDEADu, col);
    glEnd();
    ca_err("ParameterIiv_begin_bad");
    glBegin(GL_POINTS);
    glTextureParameterIuiv(tex, 0xDEADu, ucol);
    glEnd();
    ca_err("ParameterIuiv_begin_bad");
    glBegin(GL_POINTS);
    glGetTextureParameteriv(tex, 0xDEADu, &i);
    glEnd();
    ca_err("GetParameteriv_begin_bad");
    glBegin(GL_POINTS);
    glGetTextureParameterfv(tex, 0xDEADu, &f);
    glEnd();
    ca_err("GetParameterfv_begin_bad");
    glBegin(GL_POINTS);
    glGetTextureParameterIiv(tex, 0xDEADu, iv);
    glEnd();
    ca_err("GetParameterIiv_begin_bad");
    glBegin(GL_POINTS);
    glGetTextureParameterIuiv(tex, 0xDEADu, uv);
    glEnd();
    ca_err("GetParameterIuiv_begin_bad");
    glTextureParameteri(tex, 0xDEADu, 1);
    ca_err("Parameteri_invalid_enum");
    glTextureParameterf(tex, GL_TEXTURE_MIN_LOD, -1.25f);
    ca_err("Parameterf_negative_lod");
    glGetTextureParameterfv(tex, GL_TEXTURE_MIN_LOD, &f);
    printf("ca_lod_negative %.2f 0x%04x\n", f, (unsigned)glGetError());
    glGetTextureParameteriv(0xFFFFFFu, GL_TEXTURE_WRAP_S, &i);
    ca_err("GetParameteriv_bad_object");
    glGetTextureParameterfv(tex, 0xDEADu, &f);
    ca_err("GetParameterfv_bad_enum");
    glGetTextureParameterIiv(tex, 0xDEADu, iv);
    ca_err("GetParameterIiv_bad_enum");
    glGetTextureParameterIuiv(tex, 0xDEADu, uv);
    ca_err("GetParameterIuiv_bad_enum");
    glTextureSubImage3D(tex3, 0, 0, 0, 0, 1, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, bytes);
    ca_err("SubImage3D_no_storage");
    glCompressedTextureSubImage2D(tex, 0, 0, 0, 4, 4, GL_COMPRESSED_RED_RGTC1, 8, bytes);
    ca_err("CompressedSub2D_no_storage");
    glCompressedTextureSubImage3D(tex3, 0, 0, 0, 0, 4, 4, 1, GL_COMPRESSED_RED_RGTC1, 8, bytes);
    ca_err("CompressedSub3D_no_storage");
    glCopyTextureSubImage2D(tex, 0, 0, 0, 0, 0, 1, 1);
    ca_err("CopySub2D_no_storage");
    glCopyTextureSubImage3D(tex3, 0, 0, 0, 0, 0, 0, 1, 1);
    ca_err("CopySub3D_no_storage");
    glBegin(GL_POINTS);
    glTextureSubImage3D(tex3, -1, 0, 0, 0, -1, 1, 1, 0xDEADu, 0xDEADu, bytes);
    glEnd();
    ca_err("SubImage3D_begin");
    glBegin(GL_POINTS);
    glCompressedTextureSubImage2D(tex, -1, 0, 0, -1, 1, 0xDEADu, -1, bytes);
    glEnd();
    ca_err("CompressedSub2D_begin");
    glBegin(GL_POINTS);
    glCompressedTextureSubImage3D(tex3, -1, 0, 0, 0, -1, 1, 1, 0xDEADu, -1, bytes);
    glEnd();
    ca_err("CompressedSub3D_begin");
    glBegin(GL_POINTS);
    glCopyTextureSubImage2D(tex, -1, 0, 0, 0, 0, -1, 1);
    glEnd();
    ca_err("CopySub2D_begin");
    glBegin(GL_POINTS);
    glCopyTextureSubImage3D(tex3, -1, 0, 0, 0, 0, 0, -1, 1);
    glEnd();
    ca_err("CopySub3D_begin");
    glBindTexture(GL_TEXTURE_2D_MULTISAMPLE, texms);
    glBindTexture(GL_TEXTURE_2D_MULTISAMPLE_ARRAY, texmsa);
    ca_err("ms_bind");
    glTexStorage2DMultisample(GL_TEXTURE_2D_MULTISAMPLE, 2, GL_RGBA8, 5, 7, GL_TRUE);
    ca_err("TexStorage2DMS_valid");
    glTexStorage3DMultisample(GL_TEXTURE_2D_MULTISAMPLE_ARRAY, 2, GL_RGBA8, 5, 7, 3, GL_TRUE);
    ca_err("TexStorage3DMS_valid");
    glTextureStorage2DMultisample(texmsb, 2, GL_RGBA8, 9, 11, GL_TRUE);
    ca_err("TextureStorage2DMS_valid");
    glTextureStorage3DMultisample(texmsab, 2, GL_RGBA8, 9, 11, 4, GL_TRUE);
    ca_err("TextureStorage3DMS_valid");
    glGetTextureLevelParameteriv(texmsb, 0, GL_TEXTURE_WIDTH, &i);
    printf("ca_ms_dsa_width %d 0x%04x\n", i, (unsigned)glGetError());
    glGetTextureLevelParameteriv(texmsab, 0, GL_TEXTURE_DEPTH, &i);
    printf("ca_ms_dsa_depth %d 0x%04x\n", i, (unsigned)glGetError());
    glBindTexture(GL_TEXTURE_2D_MULTISAMPLE, texmsimg);
    glTexImage2DMultisample(GL_TEXTURE_2D_MULTISAMPLE, 2, GL_RGBA8, 6, 8, GL_TRUE);
    ca_err("TexImage2DMS_valid");
    glBindTexture(GL_TEXTURE_2D_MULTISAMPLE_ARRAY, texmsimga);
    glTexImage3DMultisample(GL_TEXTURE_2D_MULTISAMPLE_ARRAY, 2, GL_RGBA8, 6, 8, 2, GL_TRUE);
    ca_err("TexImage3DMS_valid");
    glGetTextureLevelParameteriv(texmsimg, 0, GL_TEXTURE_WIDTH, &i);
    printf("ca_ms_image_width %d 0x%04x\n", i, (unsigned)glGetError());
    glGetTextureLevelParameteriv(texmsimga, 0, GL_TEXTURE_DEPTH, &i);
    printf("ca_ms_image_depth %d 0x%04x\n", i, (unsigned)glGetError());
    glBegin(GL_POINTS);
    glTexImage2DMultisample(0xDEADu, -1, 0xDEADu, -1, -1, GL_TRUE);
    glEnd();
    ca_err("TexImage2DMS_begin");
    glBegin(GL_POINTS);
    glTexImage3DMultisample(0xDEADu, -1, 0xDEADu, -1, -1, -1, GL_TRUE);
    glEnd();
    ca_err("TexImage3DMS_begin");
    glBegin(GL_POINTS);
    glTexStorage2DMultisample(0xDEADu, -1, 0xDEADu, -1, -1, GL_TRUE);
    glEnd();
    ca_err("TexStorage2DMS_begin");
    glBegin(GL_POINTS);
    glTexStorage3DMultisample(0xDEADu, -1, 0xDEADu, -1, -1, -1, GL_TRUE);
    glEnd();
    ca_err("TexStorage3DMS_begin");
    glBegin(GL_POINTS);
    glTextureStorage2DMultisample(texmsb, -1, 0xDEADu, -1, -1, GL_TRUE);
    glEnd();
    ca_err("TextureStorage2DMS_begin");
    glBegin(GL_POINTS);
    glTextureStorage3DMultisample(texmsab, -1, 0xDEADu, -1, -1, -1, GL_TRUE);
    glEnd();
    ca_err("TextureStorage3DMS_begin");
    glTexStorage2DMultisample(0xDEADu, 1, GL_RGBA8, 4, 4, GL_TRUE);
    ca_err("TexStorage2DMS_bad_target");
    glTexStorage3DMultisample(0xDEADu, 1, GL_RGBA8, 4, 4, 2, GL_TRUE);
    ca_err("TexStorage3DMS_bad_target");
    glTextureStorage2DMultisample(0xFFFFFFu, 1, GL_RGBA8, 4, 4, GL_TRUE);
    ca_err("TextureStorage2DMS_bad_name");
    glTextureStorage3DMultisample(0xFFFFFFu, 1, GL_RGBA8, 4, 4, 2, GL_TRUE);
    ca_err("TextureStorage3DMS_bad_name");
    glGetTextureLevelParameteriv(texmsb, 0, GL_TEXTURE_WIDTH, &i);
    printf("ca_ms_preserved_width %d 0x%04x\n", i, (unsigned)glGetError());
    glGetTextureLevelParameteriv(texmsab, 0, GL_TEXTURE_DEPTH, &i);
    printf("ca_ms_preserved_depth %d 0x%04x\n", i, (unsigned)glGetError());
    glDeleteTextures(1, &texmsimg);
    glDeleteTextures(1, &texmsimga);
    glDeleteTextures(1, &texmsb);
    glDeleteTextures(1, &texmsab);
    glDeleteTextures(1, &tex);
    glDeleteTextures(1, &tex3);
    glDeleteTextures(1, &texms);
    glDeleteTextures(1, &texmsa);
    ca_err("teardown");
}
#endif
