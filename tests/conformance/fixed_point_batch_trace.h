#ifndef MGL_FIXED_POINT_BATCH_TRACE_H
#define MGL_FIXED_POINT_BATCH_TRACE_H
#include "mgl/gl.h"
#include <stdio.h>

static void brfx_error(const char *label) {
    printf("brfx_%s 0x%x\n", label, (unsigned)glGetError());
}

static void brfx_float(const char *label, GLenum pname) {
    GLfloat f[4] = {-9, -9, -9, -9};
    glGetFloatv(pname, f);
    printf("brfx_%s %.4f 0x%x\n", label, (double)f[0], (unsigned)glGetError());
}

static void fixed_point_batch_trace(void) {
    const GLfixed one = 65536, half = 32768, quarter = 16384;
    const GLfixed values[4] = {65536, 32768, 16384, 65536};
    const GLfixed mat[16] = {65536, 0, 0, 0, 0, 65536, 0, 0, 0, 0, 65536, 0, 0, 0, 0, 65536};
    GLfixed out[4] = {0};
    const GLfixed texmode[4] = {GL_MODULATE, 0, 0, 0}, wrapx[4] = {GL_CLAMP_TO_EDGE, 0, 0, 0};
    glMatrixMode(GL_MODELVIEW);
    glLoadIdentity();
    glActiveTexture(GL_TEXTURE0);
    (void)glGetError();
    glAlphaFuncx(GL_LESS, half);
    brfx_error("glAlphaFuncx_valid");
    glBegin(GL_POINTS);
    glAlphaFuncx(GL_LESS, half);
    glEnd();
    brfx_error("glAlphaFuncx_begin");
    glClearColorx(half, quarter, half, one);
    brfx_error("glClearColorx_valid");
    glBegin(GL_POINTS);
    glClearColorx(half, quarter, half, one);
    glEnd();
    brfx_error("glClearColorx_begin");
    glClearDepthx(half);
    brfx_error("glClearDepthx_valid");
    glBegin(GL_POINTS);
    glClearDepthx(half);
    glEnd();
    brfx_error("glClearDepthx_begin");
    glDepthRangex(quarter, one);
    brfx_error("glDepthRangex_valid");
    glBegin(GL_POINTS);
    glDepthRangex(quarter, one);
    glEnd();
    brfx_error("glDepthRangex_begin");
    glLineWidthx(one);
    brfx_error("glLineWidthx_valid");
    glBegin(GL_POINTS);
    glLineWidthx(one);
    glEnd();
    brfx_error("glLineWidthx_begin");
    glPolygonOffsetx(one, half);
    brfx_error("glPolygonOffsetx_valid");
    glBegin(GL_POINTS);
    glPolygonOffsetx(one, half);
    glEnd();
    brfx_error("glPolygonOffsetx_begin");
    glSampleCoveragex(half, GL_FALSE);
    brfx_error("glSampleCoveragex_valid");
    glBegin(GL_POINTS);
    glSampleCoveragex(half, GL_FALSE);
    glEnd();
    brfx_error("glSampleCoveragex_begin");
    glFogx(GL_FOG_DENSITY, half);
    brfx_error("glFogx_valid");
    glBegin(GL_POINTS);
    glFogx(GL_FOG_DENSITY, half);
    glEnd();
    brfx_error("glFogx_begin");
    glFogxv(GL_FOG_COLOR, values);
    brfx_error("glFogxv_valid");
    glBegin(GL_POINTS);
    glFogxv(GL_FOG_COLOR, values);
    glEnd();
    brfx_error("glFogxv_begin");
    glLightx(GL_LIGHT0, GL_CONSTANT_ATTENUATION, one);
    brfx_error("glLightx_valid");
    glBegin(GL_POINTS);
    glLightx(GL_LIGHT0, GL_CONSTANT_ATTENUATION, one);
    glEnd();
    brfx_error("glLightx_begin");
    glLightxv(GL_LIGHT0, GL_DIFFUSE, values);
    brfx_error("glLightxv_valid");
    glBegin(GL_POINTS);
    glLightxv(GL_LIGHT0, GL_DIFFUSE, values);
    glEnd();
    brfx_error("glLightxv_begin");
    glLightModelx(GL_LIGHT_MODEL_TWO_SIDE, one);
    brfx_error("glLightModelx_valid");
    glBegin(GL_POINTS);
    glLightModelx(GL_LIGHT_MODEL_TWO_SIDE, one);
    glEnd();
    brfx_error("glLightModelx_begin");
    glLightModelxv(GL_LIGHT_MODEL_AMBIENT, values);
    brfx_error("glLightModelxv_valid");
    glBegin(GL_POINTS);
    glLightModelxv(GL_LIGHT_MODEL_AMBIENT, values);
    glEnd();
    brfx_error("glLightModelxv_begin");
    glMaterialx(GL_FRONT_AND_BACK, GL_SHININESS, one);
    brfx_error("glMaterialx_valid");
    glBegin(GL_POINTS);
    glMaterialx(GL_FRONT_AND_BACK, GL_SHININESS, one);
    glEnd();
    brfx_error("glMaterialx_begin");
    glMaterialxv(GL_FRONT_AND_BACK, GL_DIFFUSE, values);
    brfx_error("glMaterialxv_valid");
    glBegin(GL_POINTS);
    glMaterialxv(GL_FRONT_AND_BACK, GL_DIFFUSE, values);
    glEnd();
    brfx_error("glMaterialxv_begin");
    glTexEnvx(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
    brfx_error("glTexEnvx_valid");
    glBegin(GL_POINTS);
    glTexEnvx(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
    glEnd();
    brfx_error("glTexEnvx_begin");
    glTexEnvxv(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, texmode);
    brfx_error("glTexEnvxv_valid");
    glBegin(GL_POINTS);
    glTexEnvxv(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, texmode);
    glEnd();
    brfx_error("glTexEnvxv_begin");
    glTexParameterx(GL_TEXTURE_2D, GL_TEXTURE_MIN_LOD, half);
    brfx_error("glTexParameterx_valid");
    glBegin(GL_POINTS);
    glTexParameterx(GL_TEXTURE_2D, GL_TEXTURE_MIN_LOD, half);
    glEnd();
    brfx_error("glTexParameterx_begin");
    glTexParameterxv(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, wrapx);
    brfx_error("glTexParameterxv_valid");
    glBegin(GL_POINTS);
    glTexParameterxv(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, wrapx);
    glEnd();
    brfx_error("glTexParameterxv_begin");
    glLoadMatrixx(mat);
    brfx_error("glLoadMatrixx_valid");
    glBegin(GL_POINTS);
    glLoadMatrixx(mat);
    glEnd();
    brfx_error("glLoadMatrixx_begin");
    glMultMatrixx(mat);
    brfx_error("glMultMatrixx_valid");
    glBegin(GL_POINTS);
    glMultMatrixx(mat);
    glEnd();
    brfx_error("glMultMatrixx_begin");
    glTranslatex(one, half, quarter);
    brfx_error("glTranslatex_valid");
    glBegin(GL_POINTS);
    glTranslatex(one, half, quarter);
    glEnd();
    brfx_error("glTranslatex_begin");
    glScalex(one, one, one);
    brfx_error("glScalex_valid");
    glBegin(GL_POINTS);
    glScalex(one, one, one);
    glEnd();
    brfx_error("glScalex_begin");
    glRotatex(one, 0, 0, one);
    brfx_error("glRotatex_valid");
    glBegin(GL_POINTS);
    glRotatex(one, 0, 0, one);
    glEnd();
    brfx_error("glRotatex_begin");
    glOrthox(-one, one, -one, one, one, 4 * one);
    brfx_error("glOrthox_valid");
    glBegin(GL_POINTS);
    glOrthox(-one, one, -one, one, one, 4 * one);
    glEnd();
    brfx_error("glOrthox_begin");
    glFrustumx(-one, one, -one, one, one, 4 * one);
    brfx_error("glFrustumx_valid");
    glBegin(GL_POINTS);
    glFrustumx(-one, one, -one, one, one, 4 * one);
    glEnd();
    brfx_error("glFrustumx_begin");
    glColor4x(half, quarter, half, one);
    brfx_error("glColor4x_valid");
    glBegin(GL_POINTS);
    glColor4x(half, quarter, half, one);
    glEnd();
    brfx_error("glColor4x_begin");
    glNormal3x(one, half, quarter);
    brfx_error("glNormal3x_valid");
    glBegin(GL_POINTS);
    glNormal3x(one, half, quarter);
    glEnd();
    brfx_error("glNormal3x_begin");
    glMultiTexCoord4x(GL_TEXTURE0, one, half, quarter, one);
    brfx_error("glMultiTexCoord4x_valid");
    glBegin(GL_POINTS);
    glMultiTexCoord4x(GL_TEXTURE0, one, half, quarter, one);
    glEnd();
    brfx_error("glMultiTexCoord4x_begin");
    out[0] = -7;
    glGetLightxv(GL_LIGHT0, GL_CONSTANT_ATTENUATION, out);
    printf("brfx_glGetLightxv_valid %d 0x%x\n", out[0], (unsigned)glGetError());
    glBegin(GL_POINTS);
    glGetLightxv(GL_LIGHT0, GL_CONSTANT_ATTENUATION, out);
    glEnd();
    brfx_error("glGetLightxv_begin");
    out[0] = -7;
    glGetMaterialxv(GL_FRONT, GL_SHININESS, out);
    printf("brfx_glGetMaterialxv_valid %d 0x%x\n", out[0], (unsigned)glGetError());
    glBegin(GL_POINTS);
    glGetMaterialxv(GL_FRONT, GL_SHININESS, out);
    glEnd();
    brfx_error("glGetMaterialxv_begin");
    out[0] = -7;
    glGetTexEnvxv(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, out);
    printf("brfx_glGetTexEnvxv_valid %d 0x%x\n", out[0], (unsigned)glGetError());
    glBegin(GL_POINTS);
    glGetTexEnvxv(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, out);
    glEnd();
    brfx_error("glGetTexEnvxv_begin");
    out[0] = -7;
    glGetTexParameterxv(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, out);
    printf("brfx_glGetTexParameterxv_valid %d 0x%x\n", out[0], (unsigned)glGetError());
    glBegin(GL_POINTS);
    glGetTexParameterxv(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, out);
    glEnd();
    brfx_error("glGetTexParameterxv_begin");
    brfx_float("fog_density", GL_FOG_DENSITY);
    brfx_float("current_color", GL_CURRENT_COLOR);
    /* Rejected fixed-point commands must preserve current values and materials. */
    glColor4x(quarter, half, half, one);
    (void)glGetError();
    glBegin(GL_POINTS);
    glColor4x(one, one, one, one);
    glEnd();
    brfx_error("color_rejected_error");
    brfx_float("color_preserved", GL_CURRENT_COLOR);
    glNormal3x(one, 0, 0);
    (void)glGetError();
    glBegin(GL_POINTS);
    glNormal3x(0, one, 0);
    glEnd();
    brfx_error("normal_rejected_error");
    brfx_float("normal_preserved", GL_CURRENT_NORMAL);
    glMultiTexCoord4x(GL_TEXTURE0, quarter, half, 0, one);
    (void)glGetError();
    glBegin(GL_POINTS);
    glMultiTexCoord4x(GL_TEXTURE0, one, one, one, one);
    glEnd();
    brfx_error("texcoord_rejected_error");
    brfx_float("texcoord_preserved", GL_CURRENT_TEXTURE_COORDS);
    glMaterialx(GL_FRONT_AND_BACK, GL_SHININESS, one);
    (void)glGetError();
    glBegin(GL_POINTS);
    glMaterialx(GL_FRONT_AND_BACK, GL_SHININESS, 2 * one);
    glEnd();
    brfx_error("material_rejected_error");
    {
        GLfloat f = 0;
        glGetMaterialfv(GL_FRONT, GL_SHININESS, &f);
        printf("brfx_material_preserved %.4f 0x%x\n", (double)f, (unsigned)glGetError());
    }
    glMatrixMode(GL_MODELVIEW);
    glLoadIdentity();
    (void)glGetError();
}
#endif
