#ifndef MGL_RASTER_OPERATION_TRACE_H
#define MGL_RASTER_OPERATION_TRACE_H
#include "mgl/gl.h"
#include <stdio.h>

static void raster_operation_trace(void) {
    GLubyte pixels[4] = {0xA5, 0xA5, 0xA5, 0xA5};
    GLfloat zoom[2] = {-1.f, -1.f};
    GLboolean valid = GL_FALSE;
    glPixelZoom(2.f, 3.f);
    glGetFloatv(GL_ZOOM_X, &zoom[0]);
    glGetFloatv(GL_ZOOM_Y, &zoom[1]);
    printf("ras_zoom_initial %.1f %.1f 0x%04x\n", zoom[0], zoom[1], (unsigned)glGetError());
    glBegin(GL_POINTS);
    glPixelZoom(4.f, 5.f);
    glEnd();
    printf("ras_zoom_inside 0x%04x\n", (unsigned)glGetError());
    glGetFloatv(GL_ZOOM_X, &zoom[0]);
    glGetFloatv(GL_ZOOM_Y, &zoom[1]);
    printf("ras_zoom_preserved %.1f %.1f 0x%04x\n", zoom[0], zoom[1], (unsigned)glGetError());
    glWindowPos3f(8.f, 9.f, 0.25f);
    glGetBooleanv(GL_CURRENT_RASTER_POSITION_VALID, &valid);
    printf("ras_window_valid %d 0x%04x\n", valid, (unsigned)glGetError());
    glBegin(GL_POINTS);
    glWindowPos2f(1.f, 2.f);
    glEnd();
    printf("ras_window_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glRasterPos4f(1.f, 2.f, 3.f, 1.f);
    glEnd();
    printf("ras_pos_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glRasterPos2d(0.0, 0.0);
    glEnd();
    printf("ras_posd_inside 0x%04x\n", (unsigned)glGetError());
    {
        const GLfloat fv[4] = {0.f, 0.f, 0.f, 1.f};
        const GLdouble dv[4] = {0., 0., 0., 1.};
        const GLint iv[3] = {3, 4, 5};
        const GLshort sv[3] = {3, 4, 5};
        glBegin(GL_POINTS);
        glRasterPos2fv(fv);
        glEnd();
        printf("ras_pos2fv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glRasterPos3fv(fv);
        glEnd();
        printf("ras_pos3fv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glRasterPos4fv(fv);
        glEnd();
        printf("ras_pos4fv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glRasterPos2dv(dv);
        glEnd();
        printf("ras_pos2dv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glRasterPos3dv(dv);
        glEnd();
        printf("ras_pos3dv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glRasterPos4dv(dv);
        glEnd();
        printf("ras_pos4dv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glWindowPos3d(5., 6., 0.25);
        glEnd();
        printf("ras_win3d_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glWindowPos2i(5, 6);
        glEnd();
        printf("ras_win2i_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glWindowPos3iv(iv);
        glEnd();
        printf("ras_win3iv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glWindowPos2sv(sv);
        glEnd();
        printf("ras_win2sv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glWindowPos3fv(fv);
        glEnd();
        printf("ras_win3fv_inside 0x%04x\n", (unsigned)glGetError());
        glBegin(GL_POINTS);
        glWindowPos2dv(dv);
        glEnd();
        printf("ras_win2dv_inside 0x%04x\n", (unsigned)glGetError());
    }
    glBegin(GL_POINTS);
    glDrawPixels(-1, 1, 0xDEAD, 0xDEAD, NULL);
    glEnd();
    printf("ras_draw_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glDrawPixels(0, 0, GL_RGBA, GL_UNSIGNED_BYTE, NULL);
    glEnd();
    printf("ras_draw_empty_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glBitmap(-1, 1, 0.f, 0.f, 0.f, 0.f, NULL);
    glEnd();
    printf("ras_bitmap_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glBitmap(0, 0, 0.f, 0.f, 0.f, 0.f, NULL);
    glEnd();
    printf("ras_bitmap_empty_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glReadPixels(0, 0, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, pixels);
    glEnd();
    printf("ras_read_inside 0x%04x %d\n", (unsigned)glGetError(),
           pixels[0] == 0xA5 && pixels[3] == 0xA5);
    glBegin(GL_POINTS);
    glReadPixels(0, 0, -1, 1, 0xDEAD, 0xDEAD, pixels);
    glEnd();
    printf("ras_read_invalid_inside 0x%04x %d\n", (unsigned)glGetError(),
           pixels[0] == 0xA5 && pixels[3] == 0xA5);
    glBegin(GL_POINTS);
    glReadPixels(0, 0, 0, 0, GL_RGBA, GL_UNSIGNED_BYTE, pixels);
    glEnd();
    printf("ras_read_empty_inside 0x%04x %d\n", (unsigned)glGetError(),
           pixels[0] == 0xA5 && pixels[3] == 0xA5);
    glBegin(GL_POINTS);
    glCopyPixels(0, 0, -1, 1, 0xDEAD);
    glEnd();
    printf("ras_copy_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glCopyPixels(0, 0, 0, 0, GL_COLOR);
    glEnd();
    printf("ras_copy_empty_inside 0x%04x\n", (unsigned)glGetError());
    glReadPixels(0, 0, -1, 1, GL_RGBA, GL_UNSIGNED_BYTE, pixels);
    printf("ras_read_bad_dims 0x%04x\n", (unsigned)glGetError());
    glCopyPixels(0, 0, -1, 1, GL_COLOR);
    printf("ras_copy_bad_dims 0x%04x\n", (unsigned)glGetError());
    glCopyPixels(0, 0, 0, 0, 0xDEAD);
    printf("ras_copy_bad_enum 0x%04x\n", (unsigned)glGetError());
    glNewList(9480, GL_COMPILE);
    glBegin(GL_POINTS);
    glCopyPixels(0, 0, -1, 1, 0xDEAD);
    glEnd();
    glEndList();
    printf("ras_copy_list_compile 0x%04x\n", (unsigned)glGetError());
    glCallList(9480);
    printf("ras_copy_list_replay 0x%04x\n", (unsigned)glGetError());
    glDeleteLists(9480, 1);
    glNewList(9481, GL_COMPILE_AND_EXECUTE);
    glBegin(GL_POINTS);
    glCopyPixels(0, 0, -1, 1, 0xDEAD);
    glEnd();
    glEndList();
    printf("ras_copy_list_execute 0x%04x\n", (unsigned)glGetError());
    glDeleteLists(9481, 1);
    glReadPixels(0, 0, 0, 0, GL_RGBA, GL_UNSIGNED_BYTE, pixels);
    printf("ras_read_recovery 0x%04x\n", (unsigned)glGetError());
}
#endif
