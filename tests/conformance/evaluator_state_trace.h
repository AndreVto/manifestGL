#ifndef MGL_EVALUATOR_STATE_TRACE_H
#define MGL_EVALUATOR_STATE_TRACE_H
#include "mgl/gl.h"
#include <stdio.h>

static void evaluator_state_trace(void) {
    const GLfloat curve[6] = {0.f, 0.f, 0.f, 1.f, 1.f, 1.f};
    const GLdouble surface[12] = {0., 0., 0., 1., 0., 0., 0., 1., 0., 1., 1., 0.};
    GLdouble domain[4] = {-1., -1., -1., -1.};
    GLfloat coeff[6] = {-1.f, -1.f, -1.f, -1.f, -1.f, -1.f};
    GLint order[2] = {-1, -1};
    GLint grid[2] = {-1, -1};
    glMap1f(GL_MAP1_VERTEX_3, 0.f, 1.f, 3, 2, curve);
    printf("ev_map1_setup 0x%04x\n", (unsigned)glGetError());
    glGetMapdv(GL_MAP1_VERTEX_3, GL_DOMAIN, domain);
    printf("ev_domain1 %.1f %.1f 0x%04x\n", domain[0], domain[1], (unsigned)glGetError());
    glGetMapfv(GL_MAP1_VERTEX_3, GL_COEFF, coeff);
    printf("ev_coeff1 %.1f %.1f 0x%04x\n", coeff[0], coeff[5], (unsigned)glGetError());
    glGetMapiv(GL_MAP1_VERTEX_3, GL_ORDER, order);
    printf("ev_order1 %d 0x%04x\n", order[0], (unsigned)glGetError());
    glMap2d(GL_MAP2_VERTEX_3, 0., 1., 6, 2, 0., 1., 3, 2, surface);
    printf("ev_map2_setup 0x%04x\n", (unsigned)glGetError());
    glGetMapiv(GL_MAP2_VERTEX_3, GL_ORDER, order);
    printf("ev_order2 %d %d 0x%04x\n", order[0], order[1], (unsigned)glGetError());
    glMapGrid1f(4, 0.f, 1.f);
    glGetIntegerv(GL_MAP1_GRID_SEGMENTS, grid);
    printf("ev_grid1 %d 0x%04x\n", grid[0], (unsigned)glGetError());
    glMapGrid2d(3, 0., 1., 5, 0., 1.);
    glGetIntegerv(GL_MAP2_GRID_SEGMENTS, grid);
    printf("ev_grid2 %d %d 0x%04x\n", grid[0], grid[1], (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMap1f(GL_MAP1_VERTEX_3, 0.f, 1.f, 3, 2, curve);
    glEnd();
    printf("ev_map1_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMap1d(0xDEAD, 0., 1., 3, 2, surface);
    glEnd();
    printf("ev_map1d_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMap2f(GL_MAP2_VERTEX_3, 0.f, 1.f, 6, 2, 0.f, 1.f, 3, 2, curve);
    glEnd();
    printf("ev_map2f_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMap2d(0xDEAD, 0., 1., 6, 2, 0., 1., 3, 2, surface);
    glEnd();
    printf("ev_map2d_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMapGrid1f(3, 0.f, 1.f);
    glEnd();
    printf("ev_grid1_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMapGrid1d(0, 0., 1.);
    glEnd();
    printf("ev_grid1d_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMapGrid2f(2, 0.f, 1.f, 2, 0.f, 1.f);
    glEnd();
    printf("ev_grid2_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glMapGrid2d(-1, 0., 1., 2, 0., 1.);
    glEnd();
    printf("ev_grid2d_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glGetMapfv(GL_MAP1_VERTEX_3, GL_ORDER, coeff);
    glEnd();
    printf("ev_getmapfv_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glGetMapdv(0xDEAD, GL_DOMAIN, domain);
    glEnd();
    printf("ev_getmapdv_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glGetMapiv(GL_MAP1_VERTEX_3, GL_ORDER, order);
    glEnd();
    printf("ev_getmapiv_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glEvalMesh1(GL_POINT, 0, 1);
    glEnd();
    printf("ev_mesh1_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glEvalMesh2(0xDEAD, 0, 1, 0, 1);
    glEnd();
    printf("ev_mesh2_invalid_inside 0x%04x\n", (unsigned)glGetError());
    glBegin(GL_POINTS);
    glEvalCoord1f(0.5f);
    glEvalCoord2d(0.5, 0.5);
    glEvalPoint1(1);
    glEvalPoint2(1, 1);
    glEnd();
    printf("ev_inside_allowed 0x%04x\n", (unsigned)glGetError());
    glEvalMesh1(GL_POINT, 0, 2);
    glEvalMesh2(GL_POINT, 0, 1, 0, 1);
    printf("ev_mesh_valid 0x%04x\n", (unsigned)glGetError());
    glGetMapdv(GL_MAP1_VERTEX_3, GL_DOMAIN, domain);
    printf("ev_domain_preserved %.1f %.1f 0x%04x\n", domain[0], domain[1], (unsigned)glGetError());
    glNewList(9460, GL_COMPILE);
    glBegin(GL_POINTS);
    glMapGrid1f(7, 0.f, 1.f);
    glEnd();
    glEndList();
    printf("ev_list_compile 0x%04x\n", (unsigned)glGetError());
    glCallList(9460);
    printf("ev_list_replay 0x%04x\n", (unsigned)glGetError());
    glGetIntegerv(GL_MAP1_GRID_SEGMENTS, grid);
    printf("ev_grid_preserved %d 0x%04x\n", grid[0], (unsigned)glGetError());
    glDeleteLists(9460, 1);
    glNewList(9461, GL_COMPILE);
    glBegin(GL_POINTS);
    glMap1f(GL_MAP1_VERTEX_3, 0.f, 1.f, 3, 2, curve);
    glMap2d(GL_MAP2_VERTEX_3, 0., 1., 6, 2, 0., 1., 3, 2, surface);
    glMapGrid2f(9, 0.f, 1.f, 9, 0.f, 1.f);
    glEnd();
    glEndList();
    printf("ev_maps_compile 0x%04x\n", (unsigned)glGetError());
    glCallList(9461);
    printf("ev_maps_replay 0x%04x\n", (unsigned)glGetError());
    glGetIntegerv(GL_MAP2_GRID_SEGMENTS, grid);
    printf("ev_grid2_preserved %d %d 0x%04x\n", grid[0], grid[1], (unsigned)glGetError());
    glDeleteLists(9461, 1);
}
#endif
